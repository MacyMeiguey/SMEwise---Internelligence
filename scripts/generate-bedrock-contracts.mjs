import ts from 'typescript';
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

// Rebuild model response contracts from the types actually consumed by the UI.
const widgets = 'client/src/components/widgets/';
const definitions = {
  startup: [widgets + 'StartupRegistrationWidget.tsx', 'StartupGuide'],
  'office-location': [widgets + 'OfficeLocationWidget.tsx', 'OfficeLocationPlan'],
  'risk-analyzer': [widgets + 'RiskAnalyzerWidget.tsx', 'RiskPlan'],
  'fund-allocation': [widgets + 'FundAllocationWidget.tsx', 'FundAllocationPlan'],
  'revenue-projection': [widgets + 'RevenueProjectionWidget.tsx', 'RevenueProjectionPlan'],
  'loans-funding': [widgets + 'LoansFundingWidget.tsx', 'LoansFundingPlan'],
  'investor-funding': [widgets + 'InvestorFundingWidget.tsx', 'InvestorFundingPlan'],
  'competitor-pricing': [widgets + 'CompetitorPricingWidget.tsx', 'CompetitorAnalysisResult'],
  'smart-pricing': [widgets + 'SmartPricingWidget.tsx', 'SmartPricingData'],
  marketing: [widgets + 'MarketingPlan.tsx', 'MarketingPlan'],
  'marketing-guidelines': [widgets + 'MarketingGuidelines.tsx', 'MarketingGuidelines'],
  'marketing-forecast': [widgets + 'MarketingForecast.tsx', 'MarketingForecast'],
  'analytics-dashboard': ['client/src/types/index.ts', 'AnalyticsDashboardData'],
  'document-generator': [widgets + 'DocumentGeneratorWidget.tsx', 'GeneratedDocument'],
};

const config = ts.readConfigFile('client/tsconfig.json', ts.sys.readFile);
const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, resolve('client'));
const program = ts.createProgram(parsed.fileNames, parsed.options);
const checker = program.getTypeChecker();

function schema(type, trail = new Set()) {
  const flags = type.flags;
  if (flags & ts.TypeFlags.StringLiteral) return { type: 'string', enum: [type.value] };
  if (flags & ts.TypeFlags.NumberLiteral) return { type: 'number', enum: [type.value] };
  if (flags & ts.TypeFlags.String) return { type: 'string' };
  if (flags & ts.TypeFlags.Number) return { type: 'number' };
  if (flags & ts.TypeFlags.BooleanLike) return { type: 'boolean' };
  if (flags & ts.TypeFlags.Null) return { type: 'null' };
  if (type.isUnion()) {
    const parts = type.types.filter((t) => !(t.flags & ts.TypeFlags.Undefined));
    return parts.length === 1 ? schema(parts[0], trail) : { anyOf: parts.map((t) => schema(t, trail)) };
  }
  if (checker.isArrayType(type)) {
    return { type: 'array', items: schema(checker.getTypeArguments(type)[0], trail) };
  }
  if (trail.has(type)) throw new Error('Recursive response type is not supported');
  if (!(flags & ts.TypeFlags.Object)) throw new Error(`Unsupported type: ${checker.typeToString(type)}`);
  const next = new Set(trail).add(type);
  const properties = {};
  const required = [];
  for (const property of checker.getPropertiesOfType(type)) {
    const declaration = property.valueDeclaration ?? property.declarations?.[0];
    if (!declaration) throw new Error(`Missing declaration for ${property.name}`);
    const item = schema(checker.getTypeOfSymbolAtLocation(property, declaration), next);
    const description = ts.displayPartsToString(property.getDocumentationComment(checker));
    properties[property.name] = description ? { ...item, description } : item;
    if (!(property.flags & ts.SymbolFlags.Optional)) required.push(property.name);
  }
  if (!Object.keys(properties).length) throw new Error(`Empty contract: ${checker.typeToString(type)}`);
  return { type: 'object', properties, required };
}

const contracts = {};
for (const [feature, [file, name]] of Object.entries(definitions)) {
  const source = program.getSourceFile(resolve(file));
  const declaration = source?.statements.find((node) => ts.isInterfaceDeclaration(node) && node.name.text === name);
  if (!declaration) throw new Error(`Cannot find ${name} in ${file}`);
  contracts[feature] = schema(checker.getTypeAtLocation(declaration));
}
mkdirSync('server/src/bedrock', { recursive: true });
writeFileSync('server/src/bedrock/contracts.ts',
  '// Generated by scripts/generate-bedrock-contracts.mjs. Do not edit manually.\n' +
  "import type { JsonSchema } from './schema.js'\n\n" +
  `export const FEATURE_CONTRACTS: Record<string, JsonSchema> = ${JSON.stringify(contracts, null, 2)}\n`);
console.log(`Generated ${Object.keys(contracts).length} response contracts.`);
