export default function SectionTabBar({ activeSection, onTabClick }: SectionTabBarProps) {
  function handleTabClick(tab: typeof TABS[number]) {
    onTabClick(tab.label);
    const el = document.getElementById(tab.id);
    if (el) {
      el.scrollIntoView({ behavior: "smooth", block: "start" });
    }
  }

  return (
    <nav
      className="md:hidden fixed bottom-0 left-0 right-0 z-50 bg-[#1a1728] border-t border-[#3d3660]"
      aria-label="Section navigation"
    >
      <div className="flex items-stretch py-2">
        {TABS.map((tab) => {
          const isActive = activeSection === tab.label;
          return (
            <button
              key={tab.label}
              type="button"
              onClick={() => handleTabClick(tab)}
              className={`flex flex-col items-center justify-center flex-1 gap-1 px-1 py-1 text-[10px] font-medium transition-all duration-200
                ${isActive
                  ? "text-[#a78bfa] border-t-2 border-[#7c3aed] -mt-0.5"
                  : "text-[#6b6890] hover:text-[#a78bfa]"
                }`}
              aria-label={`Navigate to ${tab.label} section`}
              aria-current={isActive ? "page" : undefined}
            >
              {tab.icon}
              <span>{tab.label}</span>
            </button>
          );
        })}
      </div>
    </nav>
  );
}
